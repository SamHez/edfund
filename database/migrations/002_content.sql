CREATE TABLE IF NOT EXISTS cms_templates (
 id CHAR(64) PRIMARY KEY,
 kind VARCHAR(40) NOT NULL,
 label VARCHAR(160) NOT NULL,
 html MEDIUMTEXT NOT NULL,
 fields MEDIUMTEXT NOT NULL,
 defaults MEDIUMTEXT NOT NULL,
 approved TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS cms_media (
 id CHAR(64) PRIMARY KEY,
 path VARCHAR(500) NOT NULL,
 label VARCHAR(255) NOT NULL,
 width INT NOT NULL,
 height INT NOT NULL,
 srcset TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS cms_documents (
 slug VARCHAR(50) PRIMARY KEY,
 label VARCHAR(100) NOT NULL,
 shell MEDIUMTEXT NOT NULL,
 source_hash CHAR(64) NOT NULL,
 version INT NOT NULL DEFAULT 1,
 draft_id BIGINT UNSIGNED NULL,
 published_id BIGINT UNSIGNED NULL,
 updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS cms_revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 document_slug VARCHAR(50) NOT NULL,
 content MEDIUMTEXT NOT NULL,
 action VARCHAR(20) NOT NULL,
 owner_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL,
 INDEX document_history (document_slug,id),
 FOREIGN KEY (document_slug) REFERENCES cms_documents(slug),
 FOREIGN KEY (owner_id) REFERENCES cms_users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
